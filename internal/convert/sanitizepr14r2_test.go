// Regression tests for PR #14 round 2. Two of the three are second-order: they
// are defects in the round-one FIXES, not in what those fixes replaced.

// TestIndirectLengthPayloadCannotPoisonTheIndex is the one that showed round
// one's residual was exploitable rather than merely theoretical.
//
// Round one excluded only DIRECT-length payloads from the object index, and
// said in as many words that a payload could therefore still poison the index
// "only if it sits inside a stream whose own length is indirect". Review built
// exactly that: an indirect-length stream whose payload carries an aligned
// "endstream" followed by a decoy naming the very object its own length refers
// to. pdfStreamRanges then returned five bytes of a much longer payload,
// leaving the tail exposed to redactEngineIdentity.
//
// A bound nobody tried is a bound nobody has. This one was tried.
func TestIndirectLengthPayloadCannotPoisonTheIndex(t *testing.T) {
	real := []byte("the real payload, much longer than five bytes\n")
	// The payload of the indirect-length stream: an aligned endstream five
	// bytes in, then a decoy redefining object 7.
	poison := []byte("AAAAA\nendstream\n7 0 obj\n5\nendobj\nBBBBB\n")

	var buf bytes.Buffer
	buf.WriteString("%PDF-1.4\n")
	fmt.Fprintf(&buf, "7 0 obj\n%d\nendobj\n", len(poison))
	buf.WriteString("1 0 obj\n<< /Length 7 0 R >>\nstream\n")
	buf.Write(poison)
	buf.WriteString("endstream\nendobj\n")
	fmt.Fprintf(&buf, "2 0 obj\n<< /Length %d >>\nstream\n", len(real))
	buf.Write(real)
	buf.WriteString("endstream\nendobj\n")
	buf.WriteString("trailer\n<< /Size 8 >>\nstartxref\n0\n%%EOF\n")
	raw := buf.Bytes()

	ranges, err := pdfStreamRanges(raw)
	if err != nil {
		t.Fatalf("pdfStreamRanges: %v", err)
	}
	if len(ranges) != 2 {
		t.Fatalf("got %d ranges, want 2", len(ranges))
	}

	// The whole poisoned payload must be protected, not the first five bytes.
	tail := bytes.Index(raw, []byte("BBBBB"))
	if tail < 0 {
		t.Fatal("fixture lost its own payload")
	}
	if !inAnyRange(ranges, tail) {
		t.Errorf("the tail of the indirect-length stream at %d is outside %v -- "+
			"redactEngineIdentity may rewrite it", tail, ranges)
	}

	if _, err := pdfNonStreamBytes(raw); err != nil {
		t.Errorf("the verifier's independent index was poisoned by the same payload: %v", err)
	}
}

// TestCommentBetweenDictionaryAndStreamKeyword covers a REGRESSION the round-one
// structural rule introduced.
//
// A comment may appear anywhere whitespace may (ISO 32000-1 7.2.4), so
// ">> %comment\nstream" is a valid stream header. Requiring the keyword to
// follow ">>" over whitespace only made both walkers fail to recognise such a
// stream at all -- its payload was then exposed to the redaction and read as
// file structure by the verifier. The lexical version this replaced did
// recognise these files, so the new rule was strictly worse here until it
// learned about comments.
func TestCommentBetweenDictionaryAndStreamKeyword(t *testing.T) {
	body := []byte("payload with startxref and %%EOF inside it\n")

	for _, tc := range []struct{ name, between string }{
		{"single comment", " %generated by something\n"},
		{"comment then blank line", " %a comment\n\n"},
		{"two comments", "%first\n%second\n"},
		{"whitespace only", "\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			raw := []byte("%PDF-1.4\n1 0 obj\n<< /Length " + fmt.Sprint(len(body)) + " >>" +
				tc.between + "stream\n" + string(body) + "endstream\nendobj\n" +
				"trailer\n<< /Size 2 >>\nstartxref\n0\n%%EOF\n")

			ranges, err := pdfStreamRanges(raw)
			if err != nil {
				t.Fatalf("pdfStreamRanges: %v", err)
			}
			if len(ranges) != 1 {
				t.Fatalf("got %d ranges, want 1 -- the stream was not recognised, so its "+
					"payload is exposed to the redaction", len(ranges))
			}
			at := bytes.Index(raw, []byte("payload with startxref"))
			if !inAnyRange(ranges, at) {
				t.Errorf("the payload at %d is outside %v", at, ranges)
			}

			outside, err := pdfNonStreamBytes(raw)
			if err != nil {
				t.Fatalf("pdfNonStreamBytes: %v", err)
			}
			if got := bytes.Count(outside, []byte("startxref")); got != 1 {
				t.Errorf("startxref count = %d, want 1 -- the verifier read the payload "+
					"as file structure", got)
			}
		})
	}
}

// TestEmptyContentTypeIsNotADeclaration covers the third round-two finding,
// which is a defect in the SANI-09 check itself.
//
// rewriteContentTypes preserves whatever the input wrote, so
// `ContentType=""` -- or the attribute missing entirely -- survived into the
// output. A substring match on PartName read that as declared, the XML root
// check also passed, and sanitizeFile delivered a package whose main part
// nothing describes. Office will not open it: exactly the invalid output the
// check exists to reject.
func TestEmptyContentTypeIsNotADeclaration(t *testing.T) {
	requireVerifierBinaries(t)

	cases := []struct {
		name  string
		types string
		want  bool // true = must verify clean
	}{
		{
			name:  "Override with an empty ContentType",
			types: `<Override PartName="/word/document.xml" ContentType=""/>`,
			want:  false,
		},
		{
			name:  "Override with no ContentType attribute at all",
			types: `<Override PartName="/word/document.xml"/>`,
			want:  false,
		},
		{
			name:  "Override with a whitespace-only ContentType",
			types: `<Override PartName="/word/document.xml" ContentType="   "/>`,
			want:  false,
		},
		{
			name:  "Default with an empty ContentType",
			types: `<Default Extension="xml" ContentType=""/>`,
			want:  false,
		},
		{
			name:  "a real Override",
			types: `<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>`,
			want:  true,
		},
		{
			name:  "a real Default",
			types: `<Default Extension="xml" ContentType="application/xml"/>`,
			want:  true,
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			path := buildOOXMLPackage(t, map[string][]byte{
				"[Content_Types].xml": []byte(`<?xml version="1.0"?>` +
					`<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">` +
					tc.types + `</Types>`),
				"word/document.xml": []byte(`<?xml version="1.0"?><document/>`),
			})
			_, err := verifySanitized(context.Background(), engineExec{}, "docx", path)
			if tc.want && err != nil {
				t.Errorf("a validly declared main part was rejected: %v", err)
			}
			if !tc.want && err == nil {
				t.Error("a main part with no usable content type was accepted; Office " +
					"cannot open that package")
			}
		})
	}
}

// TestContentTypeDeclarationIsParsedNotGreped pins the reason the check moved
// from a substring match to a parse: a substring match cannot tell an attribute
// on one element from an attribute on another.
func TestContentTypeDeclarationIsParsedNotGreped(t *testing.T) {
	// PartName and a non-empty ContentType, on DIFFERENT elements.
	split := []byte(`<?xml version="1.0"?>` +
		`<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">` +
		`<Override PartName="/word/document.xml"/>` +
		`<Override PartName="/word/styles.xml" ContentType="application/xml"/>` +
		`</Types>`)
	if contentTypeDeclares(split, "word/document.xml") {
		t.Error("a ContentType belonging to a different Override was read as declaring " +
			"word/document.xml")
	}

	// And the same bytes, correctly paired.
	joined := []byte(`<?xml version="1.0"?>` +
		`<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">` +
		`<Override PartName="/word/document.xml" ContentType="application/xml"/>` +
		`</Types>`)
	if !contentTypeDeclares(joined, "word/document.xml") {
		t.Error("a correctly paired Override was not recognised")
	}
}
